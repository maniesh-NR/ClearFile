        b = write_fixture("return_b.clearfile.json", clearfile_return(240050))
        manifest = write_manifest("manifest_return.json", [
            {"sha256": sha256(a), "path": a, "provenance": "synthetic",
             "origin": "test_re_tools.py generated"},
            {"sha256": sha256(b), "path": b, "provenance": "synthetic",
             "origin": "test_re_tools.py generated"},
        ])
        result = run_tool("re_diff.py", [a, b, "--manifest", manifest])
        self.assertEqual(result.returncode, 0, result.stderr)
        # One W-2 wage changed, same field width: exactly one differing

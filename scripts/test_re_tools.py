"""test_re_tools.py — unit tests for the Stage-2 RE Phase 1-3 tools
(scripts/re_entropy.py, re_magic.py, re_diff.py).

LEGAL-1 discipline: every fixture in this suite is SYNTHETIC —
program-generated bytes/text written at runtime under the gitignored
fixtures/re/ path (ADR-012 mechanic (a)). Nothing here is derived from a
proprietary file. The differential pair is synthesized inside the Stage-2
DoD's mandatory spec family #1 (the clearfile.json envelope), satisfying
the gate's "differential tool exercised on a synthesized pair inside the
mandatory set" rule.

The suite pins the security contract (Stage-2 entry gate, binding; D38):
- write-free (the read-only-fixture-dir test proves no tool writes);
- resource-bounded (each cap — size, blocks, hits, regions, timeout —
  has a refusal-on-oversize test: clean message + exit 3, never a crash);
- crash-safe (the ENG-1-shaped battery: empty, one-byte, truncated and
  adversarial shapes report, never throw);
- the differential tool's §7.1 provenance-manifest refusal (missing
  manifest / missing entry / bad provenance).

Run: python3 scripts/test_re_tools.py   (repo root; CI: hygiene re-tooling)
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE_DIR = os.path.join(ROOT, "fixtures", "re", "unit")

SYNTH_HEADER = (b"# synthetic fixture (scripts/test_re_tools.py) "
                 b"- program-generated, no proprietary content\n")


def run_tool(script: str, args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, os.path.join(ROOT, "scripts", script), *args],
        capture_output=True, text=True, timeout=120, cwd=ROOT)


def write_fixture(name: str, data: bytes) -> str:
    os.makedirs(FIXTURE_DIR, exist_ok=True)
    path = os.path.join(FIXTURE_DIR, name)
    with open(path, "wb") as f:
        f.write(data)
    return path


def clearfile_return(wages: int) -> bytes:
    """A synthetic v2-envelope clearfile.json (spec family #1 of the
    Stage-2 DoD mandatory set), pretty-printed so a single-field change
    stays byte-local (the classic Phase-3 single-input differential)."""
    doc = {
        "format": "clearfile-return",
        "version": 2,
        "app": "ClearFile 1.0.1 (synthetic)",
        "savedAt": "2026-11-22T00:00:00.000Z",
        "filing": {
            "taxYear": 2025,
            "filingStatus": "single",
            "w2s": [{"employer": "Example W-2", "wages": wages,
                     "withholding": 0}],
            "dependents": [],
        },
    }
    return (SYNTH_HEADER
            + json.dumps(doc, indent=2, sort_keys=True).encode("utf-8")
            + b"\n")


def write_manifest(name: str, entries: list[dict]) -> str:
    os.makedirs(FIXTURE_DIR, exist_ok=True)
    path = os.path.join(FIXTURE_DIR, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"entries": entries}, f, indent=2)
    return path


def sha256(path: str) -> str:
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()



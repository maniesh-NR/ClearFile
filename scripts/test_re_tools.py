    # --- The write-free posture proof --------------------------------------

    def test_read_only_fixture_dir_all_tools_exit_clean(self):
        import random
        random.seed(2028)
        entropy_path = write_fixture("ro_entropy.bin",
                                     bytes(random.randrange(256)
                                           for _ in range(8192)))
        magic_path = write_fixture("ro_magic.bin", b"MZ" + b"\x00" * 128)
        a = write_fixture("ro_a.clearfile.json", clearfile_return(240000))
        b = write_fixture("ro_b.clearfile.json", clearfile_return(240050))
        manifest = write_manifest("manifest_ro.json", [
            {"sha256": sha256(a), "path": a, "provenance": "synthetic",
             "origin": "test"},
            {"sha256": sha256(b), "path": b, "provenance": "synthetic",
             "origin": "test"},
        ])
        before = sorted(os.listdir(FIXTURE_DIR))
        # Drop ALL write permission from the fixture directory: a tool that
        # writes anywhere inside it now fails loudly (the write-free proof
        # — the contract's "read-only-fixture-dir test").
        os.chmod(FIXTURE_DIR, 0o555)
        try:
            runs = [
                run_tool("re_entropy.py", [entropy_path]),
                run_tool("re_magic.py", [magic_path]),
                run_tool("re_diff.py", [a, b, "--manifest", manifest]),
            ]
            for result in runs:
                self.assertNotIn("Traceback", result.stderr)
            self.assertEqual(runs[0].returncode, 0, runs[0].stderr)
            self.assertEqual(runs[1].returncode, 0, runs[1].stderr)
            self.assertEqual(runs[2].returncode, 0, runs[2].stderr)
        finally:
            os.chmod(FIXTURE_DIR, 0o755)
        after = sorted(os.listdir(FIXTURE_DIR))
        self.assertEqual(before, after, "a tool wrote into the fixture dir")



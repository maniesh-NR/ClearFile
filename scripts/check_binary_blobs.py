def tracked_files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"],
        capture_output=True, check=True,
    ).stdout
    return [p.decode("utf-8", "surrogateescape")
            for p in out.split(b"\x00") if p]


def is_binary(path: str) -> bool:
    """8 KiB sniff: a NUL byte or >30% non-textual control bytes = binary."""
    try:
        with open(path, "rb") as f:
            head = f.read(8192)
    except OSError:
        # Unreadable tracked file: report it as an offender, not a crash.
        return True
    if not head:
        return False
    if b"\x00" in head:
        return True
    non_text = sum(
        1 for b in head if b < 0x09 or (0x0D < b < 0x20 and b != 0x7F))
    return non_text > 0.30 * len(head)


def main() -> int:
    try:
        files = tracked_files()
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        print(f"check_binary_blobs: cannot enumerate tracked files: {e}",
              file=sys.stderr)
        return 2

    offenders = [p for p in files
                 if p not in ALLOWED_BINARY_ASSETS and is_binary(p)]

    # ADR-012 mechanic (a) belt-and-braces: the synthetic fixture path is
    # gitignored — nothing under it may ever be tracked, binary or not.
    leaked_fixtures = [p for p in files if p.startswith("fixtures/re/")]

    if offenders or leaked_fixtures:
        print("check_binary_blobs: REFUSING — binary blobs outside the "
              "own-asset allow-list (ADR-012 mechanic (b)):", file=sys.stderr)
        for p in offenders:
            print(f"  binary not on the allow-list: {p}", file=sys.stderr)
        for p in leaked_fixtures:
            print(f"  tracked file under the gitignored fixtures/re/ path: "
                  f"{p}", file=sys.stderr)
        print("  Own-authored binaries go on the list with a provenance "
              "note; anything else is removed, never listed.",
              file=sys.stderr)
        return 1
    print(f"check_binary_blobs: clean — {len(files)} tracked files, "
          f"{len(ALLOWED_BINARY_ASSETS)} allow-listed own binaries, "
          f"no other binary blobs.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
